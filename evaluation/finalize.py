"""
Generate the final Phase 7 artefacts from measured runs (§138, §151, §171, §175):

    data/evaluation/reports/final_scorecard.json
    docs/phase7-final-scorecard.md        (scorecard + before/after)
    docs/phase7-acceptance-tests.md       (ID / scenario / expected / actual / pass-fail / evidence)

Usage: python -m evaluation.finalize --before before --after after
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from evaluation import REPORTS_DIR, DATASETS_DIR  # noqa: E402
from evaluation.report import load_run, _fmt  # noqa: E402

DOCS = os.path.join(ROOT, "docs")


def _status_counts(rows):
    out = {}
    for r in rows:
        out[r["status"]] = out.get(r["status"], 0) + 1
    return out


def scorecard(before, after):
    rows_b, rows_a = before["scorecard"], after["scorecard"]
    with open(os.path.join(REPORTS_DIR, "final_scorecard.json"), "w", encoding="utf-8") as f:
        json.dump({"evaluation_run": after["label"], "generated_at": after["manifest"]["generated_at"],
                   "manifest": after["manifest"], "status_counts": _status_counts(rows_a),
                   "rows": rows_a}, f, indent=2, ensure_ascii=False, default=str)

    L = ["# Phase 7 — Final System Scorecard", "",
         f"Run `{after['label']}` · generated {after['manifest']['generated_at']} · mode **{after['manifest']['mode']}** · "
         f"app {after['manifest']['application_version']} · corpus {after['manifest']['corpus_version']} · "
         f"graph {after['manifest']['graph_version']} · engine {after['manifest']['eligibility_engine_version']}", "",
         "Generated by `python -m evaluation.finalize` from `data/evaluation/reports/after/results.json`. "
         "Every value is measured; `NOT_MEASURED` means no measurement exists (never estimated). "
         "Offline mode mocks Groq, Tavily and Sarvam — see `docs/phase7-limitations.md`.", "",
         "| Category | Metric | Target | Actual | Status | Evidence |", "|---|---|---|---|---|---|"]
    for r in rows_a:
        tgt = "info" if r["target"] == "info" else f"{r['comparator']} {_fmt(r['target'])}"
        L.append(f"| {r['category']} | {r['metric']} | {tgt} | {_fmt(r['actual'])} | **{r['status']}** | {r['evidence']} |")
    L += ["", "Status counts — after: " + ", ".join(f"{k} {v}" for k, v in sorted(_status_counts(rows_a).items()))
          + " · before: " + ", ".join(f"{k} {v}" for k, v in sorted(_status_counts(rows_b).items())), "",
          "## Before / after (MEASURE → FIX → RE-MEASURE, §150–§151)", "",
          "Same datasets and runners, before (`reports/before`) and after (`reports/after`) the Phase 7 fixes. "
          "Dataset changes between runs: E26 label correction only (BUG-029, documented).", "",
          "| Category | Metric | Before | After | Change |", "|---|---|---|---|---|"]
    for rb, ra in zip(rows_b, rows_a):
        if rb["actual"] == ra["actual"] and rb["status"] in ("NOT_MEASURED", "INFO"):
            continue
        ch = ""
        if isinstance(rb["actual"], (int, float)) and isinstance(ra["actual"], (int, float)):
            ch = f"{ra['actual'] - rb['actual']:+.4g}"
        L.append(f"| {ra['category']} | {ra['metric']} | {_fmt(rb['actual'])} ({rb['status']}) | "
                 f"{_fmt(ra['actual'])} ({ra['status']}) | {ch} |")
    with open(os.path.join(DOCS, "phase7-final-scorecard.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


def acceptance(before, after):
    with open(os.path.join(DATASETS_DIR, "e2e_cases.json"), encoding="utf-8") as f:
        e2e = {c["case_id"]: c for c in json.load(f)["cases"]}
    with open(os.path.join(DATASETS_DIR, "adversarial_cases.json"), encoding="utf-8") as f:
        adv = {c["case_id"]: c for c in json.load(f)["cases"]}
    res_a, res_b = after["results"], before["results"]
    failed_b = {f["id"] for f in res_b["e2e"].get("failures", [])} | \
        {f["id"] for f in res_b["adversarial"].get("failures", [])}
    failed_a = {f["id"]: f for f in res_a["e2e"].get("failures", []) + res_a["adversarial"].get("failures", [])}

    L = ["# Phase 7 — Acceptance Test Matrix (§175)", "",
         f"Generated from run `{after['label']}` (offline). Expected results are the structured assertions in "
         "`evaluation/datasets/e2e_cases.json` and `adversarial_cases.json`. \"Before\" is the pre-fix baseline.", "",
         "## End-to-end journeys", "",
         "| ID | Scenario | Expected | Actual | Before | After | Evidence |", "|---|---|---|---|---|---|---|"]
    for cid, c in e2e.items():
        exp = "; ".join(f"{k}={json.dumps(v, ensure_ascii=False)[:60]}" for k, v in c["expect"].items())
        actual = "as expected" if cid not in failed_a else "; ".join(failed_a[cid].get("failures", []))[:120]
        L.append(f"| {cid} | {c['title']} | {exp} | {actual} | {'FAIL' if cid in failed_b else 'PASS'} | "
                 f"{'FAIL' if cid in failed_a else 'PASS'} | e2e_runner |")
    L += ["", "## Red-team / security", "",
          "| ID | Attack | Expected safe behaviour | Before | After | Evidence |", "|---|---|---|---|---|---|"]
    for cid, c in adv.items():
        exp = c.get("expect") or (f"absent: {c['expect_absent']}" if c.get("expect_absent") else
                                  c.get("expect_status") or f"not {c.get('expect_status_not')}"
                                  if c.get("kind") == "engine_numeric" else
                                  f"never ELIGIBLE: {c.get('expect_never_eligible')}")
        L.append(f"| {cid} | {c['attack']} | {exp} | {'FAIL' if cid in failed_b else 'PASS'} | "
                 f"{'FAIL' if cid in failed_a else 'PASS'} | adversarial_runner |")
    L += ["", "## Smoke test", "", "`python scripts/smoke_test.py --offline`: see `docs/phase7-final-evaluation.md` §20."]
    with open(os.path.join(DOCS, "phase7-acceptance-tests.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--before", default="before")
    ap.add_argument("--after", default="after")
    a = ap.parse_args()
    before, after = load_run(a.before), load_run(a.after)
    scorecard(before, after)
    acceptance(before, after)
    print("final_scorecard.json, phase7-final-scorecard.md, phase7-acceptance-tests.md written")


if __name__ == "__main__":
    main()
